import java.io.File
import kotlin.math.abs

fun main() {
    try {
        // чтение и преобразование файлов
        val numbers = File("G:\\Системное программирование\\17.txt")
            // Получаем список строк
            .readLines()
            // Разбиваем строку по пробельным символам
            .flatMap { it.split(Regex("\\s+")) }
            // Фильтруем пустые строки
            .filter { it.isNotBlank() }
            // Преобразуем строки в числа, игнорируя некорректные значения
            .mapNotNull { it.toIntOrNull() }
            // Отбираем числа
            .filter { it in -100000..100000 }

        // Проверяем, есть ли числа для обработки
        if (numbers.isEmpty()) {
            println("Файл пуст или не содержит допустимых чисел")
            return  // Завершаем программу, если чисел нет
        }

        // поиск чисел
        // Минимальное трехзначное число, делящееся на 7
        val minNumber = 105

        // Находим минимальное четырехзначное число
        val min4Znach = numbers
            // Отбираем только четырехзначные числа
            .filter { abs(it) in 1000..9999 }
            // Находим число с минимальным модулем
            .minByOrNull { abs(it) }
        // Если таких чисел нет - выводим сообщение и завершаем программу
            ?: run {
                println("В файле нет четырехзначных чисел")
                return
            }

        // Получаем последнюю цифру минимального четырехзначного числа
        val last = abs(min4Znach) % 10

        // перебор пар чисел
        var count = 0         // Счетчик подходящих пар
        var maxSum = Int.MIN_VALUE  // Максимальная сумма элементов подходящих пар

        // Перебираем все пары чисел
        for (i in 0 until numbers.size - 1) {
            val a = numbers[i]      // Первое число пары
            val b = numbers[i + 1]  // Второе число пары

            // Проверяем условия:
            // 1. Хотя бы одно число в паре меньше 105
            // 2. Последняя цифра произведения чисел равна last
            if ((a < minNumber || b < minNumber) &&
                (abs(a * b) % 10 == last)) {
                count++  // Увеличиваем счетчик подходящих пар
                maxSum = maxOf(maxSum, a + b)  // Обновляем максимальную сумму
            }
        }

        // вывод результатов
        // Если найдены подходящие пары - выводим их количество и максимальную сумму
        // Иначе выводим "0 0"
        println(if (count > 0) "$count $maxSum" else "0 0")

    } catch (e: Exception) {
        // Обработка возможных ошибок при чтении файла
        println("Ошибка при обработке файла: ${e.message}")
    }
}